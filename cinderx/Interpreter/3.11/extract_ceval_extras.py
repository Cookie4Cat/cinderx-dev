#!/usr/bin/env python3
"""Generate cinderx_ceval_extras.c from a pristine CPython v3.11.6 tree.

Mini borrow generator for the vendored 3.11 eval loop (design decision D3;
same philosophy as UpstreamBorrow's gen_cached files). The manylinux /
static-libpython runtime does not export a number of private helpers that
ceval.c, specialize.c and frame.c call; this tool copies their definitions
verbatim out of the upstream sources so the extraction is reproducible and
reviewable ("regenerate and diff" instead of trusting a hand copy).

Usage:
    extract_ceval_extras.py --upstream <cpython-3.11.6-tree> \
        [--out cinderx_ceval_extras.c]

The SYMBOLS table maps upstream file -> functions to extract, in order.
Static helpers that the extracted functions need are extracted the same way
and marked in the table. Everything is emitted verbatim; the only synthetic
lines are the section headers and the include prologue.
"""


def extract_function(text: str, name: str, path: str) -> str:
    # Find a definition: `name(` at column 0 (CPython style puts the return
    # type on the previous line) or `static ... name(` one line above.
    # Match either CPython's usual style (return type on the previous line,
    # name at column 0) or a same-line return type (e.g. "uint32_t name(").
    pattern = re.compile(
        rf"^(?:[A-Za-z_][A-Za-z0-9_ ]*?[ *]+)?{re.escape(name)}\(", re.MULTILINE
    )
    match = None
    for candidate in pattern.finditer(text):
        # Reject prose hits inside comments: a real signature line ends with
        # '(' ',' or ')' (argument list), never with running text.
        line_end = text.find("\n", candidate.start())
        line = text[candidate.start() : line_end].rstrip()
        if not line.endswith(("(", ",", ")", "{")):
            continue
        # Skip forward declarations: a ';' before the first '{' means this
        # match is a prototype, not the definition.
        tail = text[candidate.start() :]
        brace_pos = tail.find("{")
        semi_pos = tail.find(";")
        if brace_pos != -1 and (semi_pos == -1 or brace_pos < semi_pos):
            match = candidate
            break
    if match is None:
        raise SystemExit(f"error: cannot find definition of {name} in {path}")
    start = match.start()
    # Pull in the return type / qualifiers: walk back over contiguous
    # non-empty lines that don't end in ';', '}' or start with '#'.
    lines_before = text[:start].splitlines(keepends=True)
    sig_prefix = []
    for line in reversed(lines_before):
        stripped = line.strip()
        if (
            not stripped
            or stripped.endswith((";", "}", "*/"))
            or stripped.startswith(("#", "//", "/*", "*"))
        ):
            break
        sig_prefix.append(line)
    prefix = "".join(reversed(sig_prefix))

    brace = text.index("{", start)
    depth = 0
    i = brace
    in_str = in_chr = in_line_comment = in_block_comment = False
    prev = ""
    while i < len(text):
        c = text[i]
        if in_line_comment:
            if c == "\n":
                in_line_comment = False
        elif in_block_comment:
            if prev == "*" and c == "/":
                in_block_comment = False
        elif in_str:
            if c == '"' and prev != "\\":
                in_str = False
        elif in_chr:
            if c == "'" and prev != "\\":
                in_chr = False
        elif prev == "/" and c == "/":
            in_line_comment = True
        elif prev == "/" and c == "*":
            in_block_comment = True
        elif c == '"':
            in_str = True
        elif c == "'":
            in_chr = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return prefix + text[start : i + 1] + "\n"
        prev = "" if prev == "\\" else c
        i += 1
    raise SystemExit(f"error: unbalanced braces extracting {name} from {path}")


def extract_typedef(text: str, name: str, path: str) -> str:
    """Extract a `typedef enum/struct { ... } name;` block verbatim."""
    terminator = re.compile(rf"^\}} {re.escape(name)};", re.MULTILINE)
    match = terminator.search(text)
    if match is None:
        raise SystemExit(f"error: cannot find typedef {name} in {path}")
    start = text.rfind("typedef", 0, match.start())
    if start == -1:
        raise SystemExit(f"error: no typedef keyword before {name} in {path}")
    return text[start : match.end()] + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).parent / "cinderx_ceval_extras.c",
    )
    args = parser.parse_args()

    chunks = [PROLOGUE]
    for rel, names in SYMBOLS:
        src = (args.upstream / rel).read_text()
        chunks.append(
            f"\n// ==== verbatim from {rel} (v3.11.6) ===================\n"
        )
        if rel in SECTION_PREFIX:
            chunks.append(SECTION_PREFIX[rel])
        for name in names:
            if name.startswith("typedef:"):
                chunks.append("\n" + extract_typedef(src, name[8:], rel))
            else:
                chunks.append("\n" + extract_function(src, name, rel))

    args.out.write_text("".join(chunks))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
